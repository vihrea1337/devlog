-- V3 — мягкое удаление записей и выборка изменений.
--
-- Раньше DELETE стирал строку физически. Для одного клиента это нормально, но как только
-- появится второе устройство (телефон + браузер) или офлайн, оно ломается: телефон,
-- который был не в сети, никак не узнает, что запись удалили — у него её просто некому
-- забрать, и она «воскреснет» при следующей синхронизации.
--
-- Теперь при удалении остаётся «надгробие»: строка с проставленным deleted_at.
-- Содержимое (raw_text и разбор ИИ) при этом стирается сразу — пользователь удалил запись,
-- хранить её текст незачем; для синхронизации хватает id и времени.
ALTER TABLE entries ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP NULL;

-- Индекс под запрос «что изменилось после такого-то момента» (синхронизация клиентов).
CREATE INDEX IF NOT EXISTS entries_user_id_updated_at ON entries (user_id, updated_at);
