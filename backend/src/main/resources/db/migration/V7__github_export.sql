-- V7 — экспорт отчётов в GitHub: репозиторий и путь до файла-changelog, по проекту.
--
-- Идея: дневник уже умеет ИМПОРТИРОВАТЬ коммиты из GitHub (см. V4/V5) — теперь он умеет
-- и обратное: по кнопке класть готовый отчёт за период в файл в репозитории пользователя
-- (по умолчанию docs/devlog.md), чтобы рядом с настоящими коммитами был человеческий текст
-- "что и почему делалось". НЕ автоматически и НЕ один коммит на запись дневника — это была
-- бы слишком навязчивая запись в чужую историю; экспорт — ручное действие по кнопке
-- на конкретном отчёте, а обновляет один и тот же файл (см. GithubExporter.kt).
--
-- Настройки — на проекте (Projects), а не глобально на пользователе: разные проекты вполне
-- могут экспортироваться в разные репозитории (или не экспортироваться вовсе).
ALTER TABLE projects ADD COLUMN IF NOT EXISTS github_export_repo VARCHAR(200);
ALTER TABLE projects ADD COLUMN IF NOT EXISTS github_export_path VARCHAR(300);
